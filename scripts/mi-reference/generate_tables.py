#!/usr/bin/env python3
"""Writes the Plaits lookup tables the `$mi.*` modules read as Rust statics.

Usage: generate_tables.py   (run fetch.sh first)
"""
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
RESOURCES = HERE / ".src/eurorack/plaits/resources.cc"
OUT = HERE.parents[1] / "crates/modular_core/src/dsp/mi/core/tables.rs"

# (C name, element type) for every table a module reads.
TABLES = [
    ("lut_sine", "f32"),
]


def parse(source, name):
    match = re.search(
        r"const (?:float|int16_t|uint8_t|int8_t|uint16_t) %s\[\] = \{(.*?)\};" % name,
        source,
        re.S,
    )
    if match is None:
        raise SystemExit(f"{name} not found in {RESOURCES}")
    return [v.strip() for v in match.group(1).split(",") if v.strip()]


def main():
    source = RESOURCES.read_text()
    lines = [
        "//! Plaits lookup tables, generated by `scripts/mi-reference/generate_tables.py`",
        "//! from `plaits/resources.cc` at the commit `fetch.sh` pins. Do not edit.",
        "",
        "#![allow(clippy::excessive_precision)]",
        "",
    ]
    for name, ty in TABLES:
        values = parse(source, name)
        lines.append("#[rustfmt::skip]")
        lines.append(f"pub static {name.upper()}: [{ty}; {len(values)}] = [")
        for i in range(0, len(values), 4):
            lines.append("    " + ", ".join(values[i : i + 4]) + ",")
        lines.append("];")
        lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
